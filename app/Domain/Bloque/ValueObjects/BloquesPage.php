<?php

namespace App\Domain\Bloque\ValueObjects;

use App\Domain\Bloque\Entities\Bloque;

final readonly class BloquesPage
{
    /**
     * @param  list<Bloque>  $items
     */
    public function __construct(
        private array $items,
        private int $total,
        private int $perPage,
        private int $currentPage,
    ) {
    }

    /**
     * @return list<Bloque>
     */
    public function items(): array
    {
        return $this->items;
    }

    public function total(): int
    {
        return $this->total;
    }

    public function perPage(): int
    {
        return $this->perPage;
    }

    public function currentPage(): int
    {
        return $this->currentPage;
    }
}

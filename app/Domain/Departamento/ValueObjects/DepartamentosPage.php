<?php

namespace App\Domain\Departamento\ValueObjects;

use App\Domain\Departamento\Entities\Departamento;

final readonly class DepartamentosPage
{
    /**
     * @param  list<Departamento>  $items
     */
    public function __construct(
        private array $items,
        private int $total,
        private int $perPage,
        private int $currentPage,
    ) {
    }

    /**
     * @return list<Departamento>
     */
    public function items(): array
    {
        return $this->items;
    }

    public function total(): int
    {
        return $this->total;
    }

    public function perPage(): int
    {
        return $this->perPage;
    }

    public function currentPage(): int
    {
        return $this->currentPage;
    }
}
